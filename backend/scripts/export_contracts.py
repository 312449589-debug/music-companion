"""Generate checked-in JSON Schema and TypeScript from the Pydantic contract."""
import argparse
import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
from app.schemas.composition import Composition


def ts_type(field):
    if "$ref" in field:
        return field["$ref"].rsplit("/", 1)[1]
    if "const" in field:
        return json.dumps(field["const"])
    if "enum" in field:
        return " | ".join(json.dumps(value) for value in field["enum"])
    if "anyOf" in field:
        return " | ".join(ts_type(item) for item in field["anyOf"])
    kind = field.get("type")
    if kind == "array":
        return "Array<" + ts_type(field["items"]) + ">"
    if kind == "object" and isinstance(field.get("additionalProperties"), dict):
        return "Record<string, " + ts_type(field["additionalProperties"]) + ">"
    return {"integer": "number", "number": "number", "boolean": "boolean",
            "string": "string", "null": "null"}[kind]


def render_interface(name, model):
    required = model.get("required", [])
    lines = [f"export interface {name} {{"]
    for name, field in model["properties"].items():
        optional = "" if name in required else "?"
        lines.append(f"  {name}{optional}: {ts_type(field)};")
    return "\n".join(lines + ["}"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = Composition.model_json_schema()
    models = list(schema.get("$defs", {}).items()) + [("Composition", schema)]
    ts = "// Generated by backend/scripts/export_contracts.py. Do not edit manually.\n\n"
    ts += "\n\n".join(render_interface(name, model) for name, model in models) + "\n"
    outputs = {
        BACKEND / "app" / "schemas" / "composition.schema.json": json.dumps(schema, ensure_ascii=False, indent=2) + "\n",
        BACKEND.parent / "frontend" / "src" / "types" / "composition.ts": ts,
    }
    for path, text in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print(f"不同步：{path.name}，请运行 export_contracts.py 更新")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    print("数据契约与前端类型同步检查通过" if args.check else "已生成数据契约与前端类型")
    return 0


if __name__ == "__main__":
    sys.exit(main())
